"""Produce tiny trusted OTA3 image labels from committed, SHA-verified historical BINs.
This runs on GitHub Actions before compiling and does not flash hardware.
esp_app_desc_t starts at 24-byte image header + 8-byte first-segment header.
"""
from __future__ import annotations
from pathlib import Path
import hashlib
import struct

ROOT = Path(__file__).resolve().parents[1]
REFERENCES = (
    ("packages/wifi2-0.0.28/firmware.bin", "0.0.28", False,
     "2e6269f79f559a63f36d7c3f225832dbb62bcf255eb57da764958eeb5edeb624"),
    ("packages/ota3-0.0.29/firmware.bin", "0.0.29", True,
     "1e35e161df445aca08efa92d3adf42eedda57a6ebda0aadad263ae33fce0c8cf"),
)

def generate():
    rows = []
    for path, version, supports_ota3, sha in REFERENCES:
        data = (ROOT / path).read_bytes()
        assert hashlib.sha256(data).hexdigest() == sha, f"Historico adulterado: {path}"
        assert len(data) < 3145728 and data[0] == 0xE9, path
        app_offset = 24 + 8
        magic, = struct.unpack_from("<I", data, app_offset)
        assert magic == 0xABCD5432, f"App description inesperada: {path}, magic={magic:08x}"
        # Espressif esp_app_desc_t: magic/secure/reserv[2], version[32],
        # project_name[32], time[16], date[16], idf_ver[32], app_elf_sha256[32].
        elf = data[app_offset + 144:app_offset + 176]
        assert len(elf) == 32 and any(elf) and elf != bytes([255] * 32)
        c_bytes = ", ".join(f"0x{v:02x}" for v in elf)
        rows.append((c_bytes, version, supports_ota3))
    assert len({r[0] for r in rows}) == len(rows), "ELF fingerprints repetidos"
    lines = [
        "#pragma once",
        "// GENERATED by ci/ota3_image_ids.py from SHA256-checked archived BINs.",
        "// Used only for display; never authorizes boot or installation.",
        "#include <string.h>",
        "struct Ota3KnownImage { uint8_t elf_sha256[32]; const char *version; bool ota3; };",
        "static const Ota3KnownImage kOta3KnownImages[] = {",
    ]
    for fp, version, ota3 in rows:
        lines.append(f'  {{{{{fp}}}, "{version}", {"true" if ota3 else "false"}}},')
    lines += [
        "};",
        "static const Ota3KnownImage* ota3KnownImage(const esp_app_desc_t &desc) {",
        "  for (const auto &item : kOta3KnownImages) {",
        "    if (memcmp(desc.app_elf_sha256, item.elf_sha256, 32) == 0) return &item;",
        "  }",
        "  return nullptr;",
        "}",
    ]
    result = ROOT / "firmware" / "ota3_known_ids.h"
    result.write_text("\n".join(lines) + "\n")
    print("OTA3_KNOWN_IMAGE_IDS_OK:", ", ".join(x[1] for x in rows))

if __name__ == "__main__":
    generate()
